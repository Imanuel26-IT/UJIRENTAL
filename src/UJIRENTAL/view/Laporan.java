    private void aturPeriodeAwal() {
        Calendar awalBulan = Calendar.getInstance();
        awalBulan.set(Calendar.DAY_OF_MONTH, 1);

        txtPeriode1.setText(formatTanggal.format(awalBulan.getTime()));
        txtPeriode2.setText(formatTanggal.format(Calendar.getInstance().getTime()));
    }

    private void muatLaporan() {
        modelLaporan.setRowCount(0);

        Date tanggalAwal = parseTanggal(txtPeriode1.getText());
        Date tanggalAkhir = parseTanggal(txtPeriode2.getText());
        if (tanggalAwal == null || tanggalAkhir == null || tanggalAwal.after(tanggalAkhir)) {
            resetRingkasan();
            return;
        }

        List<Transaksi> semua;
        try {
            semua = transaksiController.getAllTransaksi();
        } catch (SQLException ex) {
            resetRingkasan();
            JOptionPane.showMessageDialog(this,
                    "Gagal memuat laporan: " + ex.getMessage(),
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String jenis = (String) cmbJenisLaporan.getSelectedItem();
        Set<String> mobilTersewa = new HashSet<>();
        BigDecimal totalPendapatan = BigDecimal.ZERO;
        int jumlahGratis = 0;

        for (Transaksi transaksi : semua) {
            if (!sesuaiPeriode(transaksi, tanggalAwal, tanggalAkhir)
                    || !sesuaiJenis(transaksi, jenis)) {
                continue;
            }

            tambahBaris(transaksi);
            if (transaksi.getPlatNomor() != null) {
                mobilTersewa.add(transaksi.getPlatNomor());
            }
            if (transaksi.isGratisPromo()) {
                jumlahGratis++;
            }
            if ("Selesai".equals(transaksi.getStatusTransaksi())) {
                totalPendapatan = totalPendapatan
                        .add(nilaiAtauNol(transaksi.getTotalHarga()))
                        .add(nilaiAtauNol(transaksi.getDenda()));
            }
        }

        lblTotalTransaksi.setText(String.valueOf(modelLaporan.getRowCount()));
        lblMobilTersewa.setText(String.valueOf(mobilTersewa.size()));
        lblGratisLoyalty.setText(String.valueOf(jumlahGratis));
        lblTotalPendapatan.setText(formatRupiah(totalPendapatan));
    }

    private void resetRingkasan() {
        lblTotalTransaksi.setText("0");
        lblMobilTersewa.setText("0");
        lblGratisLoyalty.setText("0");
        lblTotalPendapatan.setText(formatRupiah(BigDecimal.ZERO));
    }

    private void tambahBaris(Transaksi transaksi) {
        modelLaporan.addRow(new Object[]{
            transaksi.getIdTransaksi(),
            transaksi.getNamaPelanggan(),
            transaksi.getNamaMobil(),
            transaksi.getTanggalSewa(),
            transaksi.getTanggalKembali(),
            transaksi.getLamaSewa(),
            formatRupiah(transaksi.getTotalHarga()),
            formatRupiah(transaksi.getDenda()),
            transaksi.getStatusTransaksi()
        });
    }

    private BigDecimal nilaiAtauNol(BigDecimal nilai) {
        return nilai == null ? BigDecimal.ZERO : nilai;
    }

    // Filter
    private boolean sesuaiPeriode(Transaksi transaksi, Date awal, Date akhir) {
        if (transaksi.getTanggalSewa() == null) {
            return false;
        }
        Date tanggalSewa = normalisasiHari(transaksi.getTanggalSewa());
        Date awalNormal = normalisasiHari(awal);
        Date akhirNormal = normalisasiHari(akhir);
        return !tanggalSewa.before(awalNormal) && !tanggalSewa.after(akhirNormal);
    }

    private boolean sesuaiJenis(Transaksi transaksi, String jenis) {
        if ("Semua Transaksi".equals(jenis)) {
            return true;
        }
        if ("Gratis Loyalty".equals(jenis)) {
            return transaksi.isGratisPromo();
        }
        return jenis.equals(transaksi.getStatusTransaksi());
    }

    // Bantuan
    private Date parseTanggal(String teks) {
        try {
            return formatTanggal.parse(teks.trim());
        } catch (ParseException | NullPointerException ex) {
            return null;
        }
    }

    private Date normalisasiHari(Date tanggal) {
        Calendar kalender = Calendar.getInstance();
        kalender.setTime(tanggal);
        kalender.set(Calendar.HOUR_OF_DAY, 0);
        kalender.set(Calendar.MINUTE, 0);
        kalender.set(Calendar.SECOND, 0);
        kalender.set(Calendar.MILLISECOND, 0);
        return kalender.getTime();
    }

    private String formatRupiah(BigDecimal nilai) {
        if (nilai == null) {
            nilai = BigDecimal.ZERO;
        }
        return formatMataUang.format(nilai);
    }

